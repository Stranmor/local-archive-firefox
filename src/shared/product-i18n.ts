export const UI_LOCALES = [
  ['en', 'English'], ['ru', 'Русский'], ['uk', 'Українська'], ['de', 'Deutsch'],
  ['fr', 'Français'], ['es', 'Español'], ['pt-BR', 'Português'], ['pl', 'Polski'],
] as const;

export const UI_KEYS = Object.freeze(Object.keys(en) as UiKey[]);

export type UiLocale = typeof UI_LOCALES[number][0];

const catalogs: Record<UiLocale, LocaleMessages> = { en, ru, uk, de, fr, es, 'pt-BR': ptBr, pl };

export function resolveUiLocale(value: string | undefined): UiLocale {
  const normalized = String(value || '').replace('_', '-');
  if (normalized.toLowerCase().startsWith('pt')) return 'pt-BR';
  const short = (normalized.split('-')[0] || 'en').toLowerCase();
  return UI_LOCALES.some(([locale]) => locale === short) ? short as UiLocale : 'en';
}

export function uiText(locale: UiLocale, key: UiKey, values: Record<string, string | number> = {}): string {
  return catalogs[locale][key].replace(/\{([a-zA-Z]+)\}/gu, (_, name: string) => String(values[name] ?? `{${name}}`));
}

